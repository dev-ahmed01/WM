def test_hindi_translation_keeps_numbers_and_uses_warehouse_vocabulary(monkeypatch):
    import asyncio
    from app.services import voice_service
    src = "Scan the pallet label and count 12 cartons before posting the receipt."
    if not (ROOT / "m2m100" / "model.bin").is_file():
        pytest.skip("translation model not installed")
    monkeypatch.setattr(settings, "HINDI_TRANSLATION_MODEL_DIR", str(ROOT / "m2m100"))
    hindi = asyncio.run(voice_service.translate_to_hindi(src))
    assert "12" in hindi.translate(str.maketrans("०१२३४५६७८९", "0123456789"))
    assert "कार्टन" in hindi and "कार्ड" not in hindi      # glossary prevents 'cartons' -> 'cards'


def test_translation_is_discarded_if_a_number_changes(monkeypatch):
    import asyncio
    from app.services import voice_service
    monkeypatch.setattr(voice_service, "_translate_blocking", lambda text: "पन्द्रह कार्टन गिनें और रसीद पोस्ट करें।")
    with pytest.raises(voice_service.VoiceError) as bad:
        asyncio.run(voice_service.translate_to_hindi("Count 12 cartons and post the receipt."))
    assert bad.value.code == "VOICE_TRANSLATE_REJECTED"
    monkeypatch.setattr(voice_service, "_translate_blocking", lambda text: "Count twelve cartons.")
    with pytest.raises(voice_service.VoiceError):
        asyncio.run(voice_service.translate_to_hindi("Count 12 cartons."))
