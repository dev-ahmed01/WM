def _speak(client, text, lang):
    r = client.post("/api/v1/voice/speak", json={"text": text, "language": lang})
    assert r.status_code == 200 and r.headers["content-type"] == "audio/wav" and r.content[:4] == b"RIFF", r.text[:200]
    return r.content


def _to_webm(wav: bytes) -> bytes:
    """What Chrome/Edge MediaRecorder produces: WebM + Opus."""
    return subprocess.run(["ffmpeg", "-loglevel", "error", "-i", "pipe:0", "-c:a", "libopus", "-f", "webm", "pipe:1"],
                          input=wav, capture_output=True, check=True).stdout


def _words(text):
    import re
    return set(re.findall(r"\w+", text.lower()))


def test_status_reports_both_voices_installed(client):
    s = client.get("/api/v1/voice/status").json()
    assert s["ffmpeg"] and s["text_to_speech"] == {"en": True, "hi": True}


def test_english_round_trip_webm_opus(client):
    text = "How do I post a goods receipt for a delivery?"
    webm = _to_webm(_speak(client, text, "en"))
    r = client.post("/api/v1/voice/transcribe", files={"audio": ("rec.webm", webm, "audio/webm")}, data={"language": "auto"})
    assert r.status_code == 200, r.text
    out = r.json()
    assert out["language"] == "en"
    assert len(_words(text) & _words(out["text"])) >= 6, out


def test_hindi_round_trip_is_transcribed_in_devanagari(client):
    text = "स्कैनर काम नहीं कर रहा है, मुझे क्या करना चाहिए?"
    wav = _speak(client, text, "hi")
    r = client.post("/api/v1/voice/transcribe", files={"audio": ("rec.wav", wav, "audio/wav")}, data={"language": "hi"})
    assert r.status_code == 200, r.text
    out = r.json()
    assert out["language"] == "hi"
    assert any("ऀ" <= ch <= "ॿ" for ch in out["text"])
    assert len(_words(text) & _words(out["text"])) >= 4, out


def test_silence_and_garbage_produce_understandable_errors(client):
    silent = subprocess.run(["ffmpeg", "-loglevel", "error", "-f", "lavfi", "-i", "anullsrc=r=16000:cl=mono", "-t", "2", "-f", "wav", "pipe:1"],
                            capture_output=True, check=True).stdout
    r = client.post("/api/v1/voice/transcribe", files={"audio": ("s.wav", silent, "audio/wav")})
    assert r.status_code == 400 and r.json()["error_code"] == "VOICE_NO_SPEECH" and "try again" in r.json()["message"].lower()
    r = client.post("/api/v1/voice/transcribe", files={"audio": ("x.webm", b"not audio at all", "audio/webm")})
    assert r.status_code == 415 and r.json()["error_code"] == "VOICE_BAD_AUDIO"
    r = client.post("/api/v1/voice/transcribe", files={"audio": ("x.webm", b"", "audio/webm")})
    assert r.status_code == 400 and r.json()["error_code"] == "VOICE_EMPTY"


