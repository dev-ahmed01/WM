    return Sop(
        code, area, title, hi, tuple(PROFILE[p] for p in prof.split(",")), purpose,
        tuple(tuple(x.strip() for x in s.split("|", 1)) for s in steps), exc_c, exc_a, esc,
        safety, terms, kw,
    )


